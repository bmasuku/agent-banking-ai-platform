package com.agentbanking.platform.ledger;

import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.data.jpa.repository.Query;
import org.springframework.data.repository.query.Param;

import java.math.BigDecimal;
import java.time.Instant;
import java.util.Collection;
import java.util.List;
import java.util.UUID;

public interface LedgerEntryRepository extends JpaRepository<LedgerEntry, UUID> {

    @Query("select e from LedgerEntry e join fetch e.account where e.transaction.id = :transactionId order by e.lineNumber")
    List<LedgerEntry> findByTransactionWithAccounts(@Param("transactionId") UUID transactionId);

    @Query(value = "select e from LedgerEntry e join fetch e.transaction where e.account.id = :accountId order by e.createdAt desc, e.lineNumber desc",
            countQuery = "select count(e) from LedgerEntry e where e.account.id = :accountId")
    Page<LedgerEntry> findStatement(@Param("accountId") UUID accountId, Pageable pageable);

    @Query("""
            select coalesce(sum(case when e.side = com.agentbanking.platform.ledger.EntrySide.DEBIT then e.amount else 0 end), 0)
            from LedgerEntry e
            """)
    BigDecimal totalDebits();

    @Query("""
            select coalesce(sum(case when e.side = com.agentbanking.platform.ledger.EntrySide.CREDIT then e.amount else 0 end), 0)
            from LedgerEntry e
            """)
    BigDecimal totalCredits();

    /** Sum of credits minus debits (or the reverse) per balance type within a period, used for the income statement. */
    @Query("""
            select e.account.balanceType as balanceType, e.side as side, coalesce(sum(e.amount), 0) as total
            from LedgerEntry e
            where e.account.balanceType in :types and e.createdAt >= :from and e.createdAt < :to
            group by e.account.balanceType, e.side
            """)
    List<PeriodMovement> periodMovements(@Param("types") Collection<BalanceType> types,
                                         @Param("from") Instant from, @Param("to") Instant to);

    /**
     * Hourly net movement on an agent's e-float and cash accounts generated by customer activity.
     * Columns: bucket (timestamptz), efloat_net, cash_net.
     */
    @Query(value = """
            select date_trunc('hour', le.created_at) as bucket,
                   coalesce(sum(case when la.balance_type = 'EFLOAT'
                       then case when le.side = la.normal_side then le.amount else -le.amount end else 0 end), 0) as efloat_net,
                   coalesce(sum(case when la.balance_type = 'CASH'
                       then case when le.side = la.normal_side then le.amount else -le.amount end else 0 end), 0) as cash_net
            from ledger_entries le
                     join ledger_accounts la on la.id = le.account_id
                     join financial_transactions ft on ft.id = le.transaction_id
            where la.agent_id = :agentId
              and la.balance_type in ('EFLOAT', 'CASH')
              and ft.type in ('CASH_DEPOSIT', 'CASH_WITHDRAWAL', 'AGENT_TRANSFER_TO_CUSTOMER')
              and le.created_at >= :since and le.created_at < :until
            group by date_trunc('hour', le.created_at)
            order by bucket
            """, nativeQuery = true)
    List<Object[]> hourlyCustomerFlows(@Param("agentId") UUID agentId, @Param("since") Instant since, @Param("until") Instant until);

    interface PeriodMovement {
        BalanceType getBalanceType();

        EntrySide getSide();

        BigDecimal getTotal();
    }
}
